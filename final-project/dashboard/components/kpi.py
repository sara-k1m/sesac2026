# -*- coding: utf-8 -*-

import streamlit as st


# 1평 = 3.305785㎡
PYEONG_M2 = 3.305785


def render_kpi(f):

    k1, k2, k3, k4 = st.columns(4)

    # =====================================================
    # 거래 건수
    # =====================================================

    k1.metric(
        "거래 건수",
        f"{len(f):,}건",
    )

    # =====================================================
    # 평균 월세
    # =====================================================

    k2.metric(
        "평균 월세",
        f"{f['임대료(만원)'].mean():.1f}만원",
    )

    # =====================================================
    # 평균 보증금
    # =====================================================

    k3.metric(
        "평균 보증금",
        f"{f['보증금(만원)'].mean():,.0f}만원",
    )

    # =====================================================
    # 평당 월세
    # =====================================================

    valid = f[
        (f["임대면적"] > 0)
        & (f["임대료(만원)"].notna())
        & (f["임대면적"].notna())
    ].copy()

    if len(valid) > 0:

        valid["평당월세"] = (
            valid["임대료(만원)"]
            / (valid["임대면적"] / PYEONG_M2)
        )

        rent_per_pyeong = (
            valid["평당월세"].mean()
        )

        k4.metric(
            "평당 월세",
            f"{rent_per_pyeong:.1f}만원/평",
        )

    else:

        k4.metric(
            "평당 월세",
            "-",
        )

    # =====================================================
    # 역 500m 이내 비율
    # =====================================================

    if (
        "최근접역_거리(m)" in f.columns
        and len(f) > 0
    ):

        station_ratio = (
            f["최근접역_거리(m)"] <= 500
        ).mean() * 100

    else:

        station_ratio = 0

    # 향후 5번째 KPI가 필요하면 사용
