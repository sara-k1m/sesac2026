# components/kpi.py

# -*- coding: utf-8 -*-

import streamlit as st


# =====================================================
# 기본 설정
# =====================================================

# 1평 = 3.305785㎡
PYEONG_M2 = 3.305785


# =====================================================
# 전체 대비 증감률 계산
# =====================================================

def calc_change(current, overall):
    """
    현재 값이 전체 값과 비교해서
    몇 % 높은지 / 낮은지 계산
    """

    if overall is None or overall == 0:
        return None

    return (
        (current - overall)
        / overall
        * 100
    )


# =====================================================
# KPI
# =====================================================

def render_kpi(f, df):
    """
    f  : 현재 필터가 적용된 데이터
    df : 전체 데이터
    """

    # =================================================
    # 전체 평균 계산
    # =================================================

    # ---------------------------------------------
    # 전체 거래 건수
    # ---------------------------------------------

    overall_count = len(df)

    # ---------------------------------------------
    # 전체 평균 월세
    # ---------------------------------------------

    overall_rent = (
        df["임대료(만원)"]
        .dropna()
        .mean()
    )

    # ---------------------------------------------
    # 전체 평균 보증금
    # ---------------------------------------------

    overall_deposit = (
        df["보증금(만원)"]
        .dropna()
        .mean()
    )

    # ---------------------------------------------
    # 전체 평당 월세
    # ---------------------------------------------

    overall_valid = df[
        (df["임대면적"] > 0)
        & (df["임대료(만원)"].notna())
        & (df["임대면적"].notna())
    ].copy()

    if len(overall_valid) > 0:

        overall_valid["평당월세"] = (
            overall_valid["임대료(만원)"]
            / (
                overall_valid["임대면적"]
                / PYEONG_M2
            )
        )

        overall_rent_per_pyeong = (
            overall_valid["평당월세"]
            .mean()
        )

    else:

        overall_rent_per_pyeong = None

    # =================================================
    # 현재 조건 값
    # =================================================

    # ---------------------------------------------
    # 거래 건수
    # ---------------------------------------------

    current_count = len(f)

    # ---------------------------------------------
    # 평균 월세
    # ---------------------------------------------

    current_rent = (
        f["임대료(만원)"]
        .dropna()
        .mean()
    )

    # ---------------------------------------------
    # 평균 보증금
    # ---------------------------------------------

    current_deposit = (
        f["보증금(만원)"]
        .dropna()
        .mean()
    )

    # ---------------------------------------------
    # 평당 월세
    # ---------------------------------------------

    valid = f[
        (f["임대면적"] > 0)
        & (f["임대료(만원)"].notna())
        & (f["임대면적"].notna())
    ].copy()

    if len(valid) > 0:

        valid["평당월세"] = (
            valid["임대료(만원)"]
            / (
                valid["임대면적"]
                / PYEONG_M2
            )
        )

        current_rent_per_pyeong = (
            valid["평당월세"]
            .mean()
        )

    else:

        current_rent_per_pyeong = None

    # =================================================
    # 전체 대비 변화율
    # =================================================

    count_change = calc_change(
        current_count,
        overall_count,
    )

    rent_change = calc_change(
        current_rent,
        overall_rent,
    )

    deposit_change = calc_change(
        current_deposit,
        overall_deposit,
    )

    rent_per_pyeong_change = calc_change(
        current_rent_per_pyeong,
        overall_rent_per_pyeong,
    )

    # =================================================
    # KPI 표시
    # =================================================

    k1, k2, k3, k4 = st.columns(4)

    # =================================================
    # 거래 건수
    # =================================================

    with k1:

        st.metric(
            "거래 건수",
            f"{current_count:,}건",
            delta=(
                f"{count_change:+.1f}%"
                if count_change is not None
                else None
            ),
            help="서울 전체 데이터의 거래 건수와 비교한 값입니다.",
        )

    # =================================================
    # 평균 월세
    # =================================================

    with k2:

        st.metric(
            "평균 월세",
            f"{current_rent:.1f}만원",
            delta=(
                f"{rent_change:+.1f}%"
                if rent_change is not None
                else None
            ),
            help="서울 전체 평균 월세 대비 차이입니다.",
        )

    # =================================================
    # 평균 보증금
    # =================================================

    with k3:

        st.metric(
            "평균 보증금",
            f"{current_deposit:,.0f}만원",
            delta=(
                f"{deposit_change:+.1f}%"
                if deposit_change is not None
                else None
            ),
            help="서울 전체 평균 보증금 대비 차이입니다.",
        )

    # =================================================
    # 평당 월세
    # =================================================

    with k4:

        if current_rent_per_pyeong is not None:

            st.metric(
                "평당 월세",
                f"{current_rent_per_pyeong:.1f}만원/평",
                delta=(
                    f"{rent_per_pyeong_change:+.1f}%"
                    if rent_per_pyeong_change is not None
                    else None
                ),
                help="서울 전체 평균 평당 월세 대비 차이입니다.",
            )

        else:

            st.metric(
                "평당 월세",
                "-",
            )
